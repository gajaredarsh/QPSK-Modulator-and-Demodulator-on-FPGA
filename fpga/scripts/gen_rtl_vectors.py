"""
gen_rtl_vectors.py  --  Part A: Python golden model -> RTL parameters, LUTs, test vectors.

Place in python_codes/fixed_point/ (next to params.py and tx_nco.py) and run:
    python gen_rtl_vectors.py [--out DIR] [--symbols N]

Everything the RTL needs is derived from params.py / tx_nco.py, so there is
one source of truth. Outputs (default DIR = ../../fpga/generated):
    qpsk_params.vh    `define constants included by the Verilog files
    lut_cos.hex       NCO cosine ROM  ($readmemh)
    lut_sin.hex       NCO sine ROM    ($readmemh)
    golden_s.hex      expected TX mixer output, one 13-bit word per sample
    golden_bits.hex   expected PRBS bit pair per symbol, hex digit = {b0,b1}
"""
import argparse, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import params, tx_nco


def check_rtl_assumptions():
    # prbs7_gen.v is hand-specialised for PRBS-7, taps (1,7), shift-right.
    assert params.PRBS_LEN == 7 and tuple(params.PRBS_TAPS) == (1, 7), \
        "prbs7_gen.v only implements PRBS-7 with taps (1,7); update the RTL"
    assert params.PRBS_SEED != 0 and params.PRBS_SEED < (1 << params.PRBS_LEN)
    assert params.NCO_ACC_BITS >= params.NCO_LUT_BITS
    assert params.MIXER_OUT_BITS >= tx_nco.required_mixer_bits(params.DATAPATH_BITS)
    # python PRBS == bit-literal RTL mirror
    n = 4 * (1 << params.PRBS_LEN)
    assert np.array_equal(tx_nco.gen_bits(n), tx_nco._prbs7_rtl_reference(n, params.PRBS_SEED))
    # symbol boundaries must coincide with NCO phase 0 (RTL does not re-sync phase)
    assert (params.SAMPLES_PER_SYMBOL * params.NCO_PHASE_INC) % (1 << params.NCO_ACC_BITS) == 0, \
        "symbol length is not a whole number of carrier cycles"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "..", "..", "fpga", "generated"))
    ap.add_argument("--symbols", type=int, default=512)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    os.makedirs(out, exist_ok=True)
    check_rtl_assumptions()

    # 1. parameter header
    with open(os.path.join(out, "qpsk_params.vh"), "w") as f:
        f.write("// AUTO-GENERATED by gen_rtl_vectors.py from params.py -- do not edit\n")
        f.write("`ifndef QPSK_PARAMS_VH\n`define QPSK_PARAMS_VH\n")
        for k, v in [("SPS", params.SAMPLES_PER_SYMBOL),
                     ("NCO_ACC_BITS", params.NCO_ACC_BITS),
                     ("NCO_LUT_BITS", params.NCO_LUT_BITS),
                     ("NCO_PHASE_INC", params.NCO_PHASE_INC),
                     ("DATAPATH_BITS", params.DATAPATH_BITS),
                     ("MIXER_OUT_BITS", params.MIXER_OUT_BITS),
                     ("PRBS_SEED", f"7'h{params.PRBS_SEED:02X}"),
                     ("TB_N_SYMBOLS", a.symbols)]:
            f.write(f"`define {k} {v}\n")
        f.write("`endif\n")

    # 2. ROMs
    lut_cos, lut_sin = tx_nco.build_nco_lut()
    tx_nco.export_lut_hex(lut_cos, params.DATAPATH_BITS, os.path.join(out, "lut_cos.hex"))
    tx_nco.export_lut_hex(lut_sin, params.DATAPATH_BITS, os.path.join(out, "lut_sin.hex"))

    # 3. golden vectors from the SAME functions the Python chain uses
    n_sym, sps = a.symbols, params.SAMPLES_PER_SYMBOL
    bits = tx_nco.gen_bits(2 * n_sym)
    I, Q = tx_nco.map_qpsk(bits)
    cos_i, sin_i = tx_nco.nco_fixed(n_sym * sps)
    s = tx_nco.modulate_fixed(I, Q, cos_i, sin_i)
    tx_nco.export_lut_hex(s, params.MIXER_OUT_BITS, os.path.join(out, "golden_s.hex"))
    with open(os.path.join(out, "golden_bits.hex"), "w") as f:
        for b0, b1 in bits.reshape(-1, 2):
            f.write(f"{(int(b0) << 1) | int(b1):x}\n")

    print(f"wrote RTL params, LUTs and {n_sym} symbols ({n_sym*sps} samples) of golden vectors to {out}")


if __name__ == "__main__":
    main()
